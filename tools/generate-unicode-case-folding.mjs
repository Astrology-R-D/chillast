import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const UNICODE_VERSION = '17.0.0';
const SOURCE_URL = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/CaseFolding.txt`;
const EXPECTED_SHA256 = 'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183';
const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(rootDir, 'vendor', 'unicode', UNICODE_VERSION, 'CaseFolding.txt');
const defaultOutputPath = path.join(rootDir, 'src', 'core', 'util', 'UnicodeCaseFoldData.js');
const args = process.argv.slice(2);
const check = args.includes('--check');
const updateSource = args.includes('--update-source');
const outputIndex = args.indexOf('--output');
const outputPath = outputIndex >= 0 ? path.resolve(args[outputIndex + 1] || '') : defaultOutputPath;
const allowedArgs = new Set(['--check', '--update-source', '--output']);
const unknownArg = args.find((arg, index) => !allowedArgs.has(arg) && index !== outputIndex + 1);
if (unknownArg || (outputIndex >= 0 && !args[outputIndex + 1])) {
  throw new Error(`Unknown or incomplete argument: ${unknownArg || '--output'}`);
}
if (check && updateSource) throw new Error('--check cannot be combined with --update-source');

if (updateSource) {
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`Failed to download ${SOURCE_URL}: ${response.status}`);
  const downloaded = await response.text();
  const downloadedSha256 = createHash('sha256').update(downloaded).digest('hex');
  if (downloadedSha256 !== EXPECTED_SHA256) {
    throw new Error(`Unicode source checksum changed: expected ${EXPECTED_SHA256}, received ${downloadedSha256}`);
  }
  await mkdir(path.dirname(sourcePath), { recursive: true });
  await writeFile(sourcePath, downloaded, 'utf8');
  console.log(`Updated ${path.relative(rootDir, sourcePath)} from ${SOURCE_URL}`);
}

const source = await readFile(sourcePath, 'utf8');
if (!source.startsWith(`# CaseFolding-${UNICODE_VERSION}.txt`)) {
  throw new Error(`Unexpected Unicode case-folding data in ${sourcePath}`);
}
const sha256 = createHash('sha256').update(source).digest('hex');
if (sha256 !== EXPECTED_SHA256) {
  throw new Error(`Unicode source checksum changed: expected ${EXPECTED_SHA256}, received ${sha256}`);
}

const mappings = new Map();
for (const line of source.split(/\r?\n/)) {
  const record = line.split('#', 1)[0].trim();
  if (!record) continue;
  const [code, status, mapping] = record.split(';').map((part) => part.trim());
  if (status !== 'C' && status !== 'F') continue;
  mappings.set(
    Number.parseInt(code, 16),
    mapping.split(' ').map((value) => Number.parseInt(value, 16)),
  );
}
if (mappings.size < 1500) throw new Error(`Parsed only ${mappings.size} case-fold mappings`);

const hex = (value) => `0x${value.toString(16).toUpperCase()}`;
const rows = [...mappings]
  .sort(([left], [right]) => left - right)
  .map(([code, mapping]) => `  [${hex(code)}, [${mapping.map(hex).join(', ')}]],`)
  .join('\n');
const generated = `'use strict';

// Generated by tools/generate-unicode-case-folding.mjs. Do not edit manually.
// Unicode ${UNICODE_VERSION} CaseFolding.txt (full default C+F mappings; S/T excluded).
// Source file: vendor/unicode/${UNICODE_VERSION}/CaseFolding.txt
// Source URL: ${SOURCE_URL}
// Source SHA-256: ${sha256}
// Source copyright: © 2025 Unicode®, Inc.
// License: licenses/UNICODE-LICENSE-3.0.txt
const CASE_FOLD_MAP = new Map([
${rows}
]);

module.exports = { CASE_FOLD_MAP, UNICODE_VERSION: '${UNICODE_VERSION}' };
`;

if (check) {
  const existing = await readFile(outputPath, 'utf8').catch((error) => {
    if (error.code === 'ENOENT') return '';
    throw error;
  });
  if (existing !== generated) {
    console.error(`Unicode case-fold data is out of date: ${outputPath}`);
    console.error('Run: node tools/generate-unicode-case-folding.mjs');
    process.exitCode = 1;
  } else {
    console.log(`Unicode case-fold data is up to date (${mappings.size} mappings, ${sha256})`);
  }
} else {
  await writeFile(outputPath, generated, 'utf8');
  console.log(`Generated ${mappings.size} Unicode ${UNICODE_VERSION} mappings (${Buffer.byteLength(generated)} bytes)`);
}
